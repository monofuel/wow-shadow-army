#!/usr/bin/env python3
"""Generate lua/data/bot_quest_hubs.lua from the VMaNGOS world DB.

The bots live in WORLD coordinates. Questgiver memory only holds NPCs the
seat has SEEN, and it resets on every reload -- so a banked quest has
nothing to walk to. This table is the static world knowledge a player
reads off a guide: quest id -> where the NPC that starts it and the NPC
that ends it actually stand.

Reads (read-only, never writes):
  * world DB via `docker exec <container> mariadb ...` (same shell-out
    path as tools/gen_quest_data.py)

Writes lua/data/bot_quest_hubs.lua, required as "data.bot_quest_hubs":

    return {
    [6] = {starter = {0,-8949.9,-132.5,83.5,"Marshal McBride"},
           ender = {0,-8949.9,-132.5,83.5,"Marshal McBride"}},
    ...
    }

Creature givers only. A gameobject-started quest is absent: the bot
cannot walk to a chest the way it walks to an NPC.

Deterministic: no timestamps, everything sorted, so two runs against an
unchanged DB produce a byte-identical file.

  python3 tools/gen_bot_quest_hubs.py        # or: make bot-quest-hubs
"""

from __future__ import annotations

import argparse
import os
import sys
from typing import Dict, List, Optional, Sequence, Tuple

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from gen_quest_data import (World, load_relation, lua_string, _i, _f,
                            WOW_PATCH, DEFAULT_CONTAINER, load_template)

_REPO = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
DEFAULT_OUT = os.path.join(_REPO, "lua", "data", "bot_quest_hubs.lua")

# (map, x, y, z) -- one representative spawn, lowest creature guid.
Spawn = Tuple[int, float, float, float]
# resolved creature entries; None means that side did not resolve.
Hub = Tuple[Optional[int], Optional[int]]


def load_creature_spawns(db: World) -> Dict[int, Spawn]:
    """entry -> (map, x, y, z) for the row with the lowest guid.

    Same id1..id5 pool rule as gen_quest_data.load_creature_spawns (every
    non-zero id on the row gets the point). That helper drops guid and z;
    this table needs both, so the query stays local and the rest is shared.
    """
    rows = db.query(
        "SELECT guid,id,id2,id3,id4,id5,map,"
        "position_x,position_y,position_z FROM creature "
        "WHERE patch_min<=%d AND patch_max>=%d"
        % (WOW_PATCH, WOW_PATCH)
    )
    best_guid: Dict[int, int] = {}
    out: Dict[int, Spawn] = {}
    for r in rows:
        if len(r) < 10:
            continue
        guid = _i(r[0])
        point = (_i(r[6]), _f(r[7]), _f(r[8]), _f(r[9]))
        for col in r[1:6]:
            entry = _i(col)
            if entry <= 0:
                continue
            prev = best_guid.get(entry)
            if prev is None or guid < prev:
                best_guid[entry] = guid
                out[entry] = point
    return out


def first_spawned(entries: Sequence[int],
                  spawns: Dict[int, Spawn]) -> Optional[int]:
    """Lowest entry (entries are pre-sorted) that has a spawn row."""
    for entry in entries:
        if entry in spawns:
            return entry
    return None


def fmt(value: float) -> str:
    return "%.1f" % value


def hub_cell(entry: int, spawns: Dict[int, Spawn],
             names: Dict[int, str]) -> str:
    map_id, x, y, z = spawns[entry]
    return "{%d,%s,%s,%s,%s}" % (
        map_id, fmt(x), fmt(y), fmt(z), lua_string(names.get(entry, "")))


def emit(hubs: Dict[int, Hub], header: Sequence[str],
         spawns: Dict[int, Spawn], names: Dict[int, str]) -> str:
    lines = ["-- generated by tools/gen_bot_quest_hubs.py; do not edit by hand"]
    lines += [("-- " + line).rstrip() for line in header]
    lines.append("")
    lines.append("return {")
    for qid in sorted(hubs):
        starter, ender = hubs[qid]
        parts: List[str] = []
        if starter is not None:
            parts.append("starter = " + hub_cell(starter, spawns, names))
        if ender is not None:
            parts.append("ender = " + hub_cell(ender, spawns, names))
        lines.append("[%d] = {%s}," % (qid, ", ".join(parts)))
    lines.append("}")
    lines.append("")
    return "\n".join(lines)


def main(argv: Optional[Sequence[str]] = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("--container", default=DEFAULT_CONTAINER)
    ap.add_argument("--out", default=DEFAULT_OUT)
    args = ap.parse_args(argv)

    db = World(args.container)
    starters = load_relation(db, "creature_questrelation")
    enders = load_relation(db, "creature_involvedrelation")
    go_starters = load_relation(db, "gameobject_questrelation")
    go_enders = load_relation(db, "gameobject_involvedrelation")
    titles = load_template(db, "quest_template", "Title")
    name_rows = load_template(db, "creature_template", "name")
    names = {entry: cols[0] for entry, cols in name_rows.items()}
    spawns = load_creature_spawns(db)

    related = (set(starters) | set(enders)
               | set(go_starters) | set(go_enders))
    hubs: Dict[int, Hub] = {}
    skipped_go = 0
    skipped_nospawn = 0
    skipped_unknown = 0
    for qid in sorted(related):
        if qid not in titles:
            skipped_unknown += 1
            continue
        starter = first_spawned(starters.get(qid, ()), spawns)
        ender = first_spawned(enders.get(qid, ()), spawns)
        if starter is not None or ender is not None:
            hubs[qid] = (starter, ender)
            continue
        has_creature = qid in starters or qid in enders
        has_go = qid in go_starters or qid in go_enders
        if has_creature:
            skipped_nospawn += 1
        elif has_go:
            skipped_go += 1

    n_emitted = len(hubs)
    n_starter = sum(1 for s, _e in hubs.values() if s is not None)
    n_ender = sum(1 for _s, e in hubs.values() if e is not None)
    n_both = sum(1 for s, e in hubs.values()
                 if s is not None and e is not None)

    header = [
        "source: VMaNGOS world DB via gen_quest_data.World, WowPatch %d"
        % WOW_PATCH,
        "coords are WORLD units (yards); each giver is {map,x,y,z,name}",
        "one representative spawn per NPC = lowest creature guid",
        "lowest creature entry when a quest has several givers",
        "creature givers only; GO-started/ended quests are absent",
        "emitted %d (starter %d, ender %d, both %d); skipped GO-only %d,"
        % (n_emitted, n_starter, n_ender, n_both, skipped_go),
        "no-spawn %d, unknown-quest %d" % (skipped_nospawn, skipped_unknown),
        "regenerate: make bot-quest-hubs",
    ]

    text = emit(hubs, header, spawns, names)
    out_dir = os.path.dirname(args.out)
    if out_dir and not os.path.isdir(out_dir):
        os.makedirs(out_dir)
    with open(args.out, "w") as fh:
        fh.write(text)

    print("wrote %s" % args.out)
    print("  quests emitted     : %d" % n_emitted)
    print("  with starter       : %d" % n_starter)
    print("  with ender         : %d" % n_ender)
    print("  with both          : %d" % n_both)
    print("  skipped GO-only    : %d" % skipped_go)
    print("  skipped no-spawn   : %d" % skipped_nospawn)
    print("  skipped unknown    : %d" % skipped_unknown)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
