#!/usr/bin/env python3
"""Resample human F9 walk logs into sparse land beats.

Generic land twin of resample_human_ribbon.py (which is hard-wired to the
old-schema coast SWIM log): reads new-schema activity logs
(``observation.player.position`` on ``human_step`` rows), stitches multiple
legs into one chain, decimates by cumulative arclength, and emits beat
configs in the traverse brain's schema.

Every emitted beat is ``hook = true``: interior galleries double back in X,
so beats must retire by CAPTURE only — the brain's X-monotonic passed-band
would skip a westward run of beats (see next_sparse_beat in traverse.lua).

Stitching: legs are appended in CLI order. A leg given as ``path:reverse``
is walked backwards first. Each subsequent leg starts at its point closest
to the current chain tail, so overlapping coverage (e.g. a walk recorded in
two takes crossing the same hall) does not fold the chain back on itself.

Usage:
  python3 tools/resample_trace_beats.py LOG[:reverse] [LOG2[:reverse] ...]
      [--spacing 20.0] [--radius 8.0] [--id-prefix timbermaw]
      [--out-prefix lua/config/traverse_finale_interior_beats]
      [--goal-id NAME] [--map-id 1] [--write]

Without --write, prints the chain/beat summary and the beats to stdout.
"""

from __future__ import annotations

import argparse
import json
import math
import sys
from pathlib import Path


def read_track(path: Path) -> list[tuple[float, float, float]]:
    """Positions from human_step rows, consecutive near-duplicates dropped."""
    points: list[tuple[float, float, float]] = []
    with path.open(encoding="utf-8") as fh:
        for line in fh:
            try:
                row = json.loads(line)
            except json.JSONDecodeError:
                continue
            if row.get("type") != "human_step":
                continue
            pos = (row.get("observation") or {}).get("player", {}).get("position")
            if not pos:
                continue
            p = (float(pos["x"]), float(pos["y"]), float(pos["z"]))
            if points and planar(points[-1], p) < 1.0:
                continue
            points.append(p)
    return points


def planar(a: tuple[float, float, float], b: tuple[float, float, float]) -> float:
    return math.hypot(a[0] - b[0], a[1] - b[1])


def stitch(
    legs: list[list[tuple[float, float, float]]],
    seed: tuple[float, float, float] | None = None,
) -> list[tuple[float, float, float]]:
    """Seeding starts the chain at a known pose (e.g. a checkpoint): the
    first leg then joins at its point closest to the seed, which drops any
    recording preamble (teleports, look-arounds) before that pose."""
    chain: list[tuple[float, float, float]] = list([seed] if seed else [])
    for leg in legs:
        if not leg:
            continue
        if not chain:
            chain.extend(leg)
            continue
        tail = chain[-1]
        start = min(range(len(leg)), key=lambda i: planar(leg[i], tail))
        chain.extend(leg[start:])
    return chain


def decimate(
    chain: list[tuple[float, float, float]], spacing: float
) -> list[tuple[float, float, float]]:
    """Keep points every ``spacing`` yards of walked arclength; always the ends."""
    if len(chain) < 2:
        return list(chain)
    kept = [chain[0]]
    since = 0.0
    for prev, cur in zip(chain, chain[1:]):
        since += planar(prev, cur)
        if since >= spacing:
            kept.append(cur)
            since = 0.0
    if kept[-1] != chain[-1]:
        kept.append(chain[-1])
    return kept


def beats_payload(
    points: list[tuple[float, float, float]],
    id_prefix: str,
    radius: float,
    map_id: int,
    goal_id: str | None,
    navigation_mode: str | None = None,
    allow_jump: bool = False,
) -> dict:
    beats = []
    for index, (x, y, z) in enumerate(points, start=1):
        beat = {
            "id": f"{id_prefix}_{index:02d}",
            "x": round(x, 1),
            "y": round(y, 1),
            "z": round(z, 1),
            "radius": radius,
            "hook": True,
        }
        if navigation_mode:
            beat["navigation_mode"] = navigation_mode
        if allow_jump:
            beat["allow_jump"] = True
        beats.append(beat)
    return {
        "map_id": map_id,
        "goal_id": goal_id or beats[-1]["id"],
        "beats": beats,
    }


LUA_HEADER = """-- GENERATED by tools/resample_trace_beats.py — walked-ground beats from
-- manual F9 reference logs (see docs/traverse/reference-logs.md). Every
-- beat is hook = true: interior legs double back in X, so beats retire by
-- capture only. Do not hand-edit; re-run the tool.
"""


def emit_lua(payload: dict) -> str:
    lines = [LUA_HEADER, "return {"]
    lines.append(f"  map_id = {payload['map_id']},")
    lines.append(f'  goal_id = "{payload["goal_id"]}",')
    lines.append("  beats = {")
    for b in payload["beats"]:
        extra = ""
        if b.get("navigation_mode"):
            extra += f', navigation_mode = "{b["navigation_mode"]}"'
        if b.get("allow_jump"):
            extra += ", allow_jump = true"
        lines.append(
            f'    {{ id = "{b["id"]}", x = {b["x"]}, y = {b["y"]}, '
            f'z = {b["z"]}, radius = {b["radius"]}, hook = true{extra} }},'
        )
    lines.append("  },")
    lines.append("}")
    return "\n".join(lines) + "\n"


def main(argv: list[str]) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("logs", nargs="+", help="activity log path, optionally :reverse")
    parser.add_argument("--spacing", type=float, default=20.0)
    parser.add_argument("--radius", type=float, default=8.0)
    parser.add_argument("--id-prefix", default="timbermaw")
    parser.add_argument(
        "--out-prefix", default="lua/config/traverse_finale_interior_beats"
    )
    parser.add_argument("--goal-id", default=None)
    parser.add_argument("--map-id", type=int, default=1)
    parser.add_argument(
        "--navigation-mode",
        default=None,
        help="stamp each beat with this navigation_mode (e.g. local_steer);"
        " forward-safe — the committed intent parser ignores unknown keys",
    )
    parser.add_argument(
        "--allow-jump",
        action="store_true",
        help="stamp allow_jump=true on each beat (fork feature, forward-safe)",
    )
    parser.add_argument(
        "--seed",
        default=None,
        help="X,Y,Z chain start (e.g. a checkpoint pose); legs join at "
        "their closest point, dropping teleport/look-around preambles",
    )
    parser.add_argument("--write", action="store_true")
    args = parser.parse_args(argv)

    seed = None
    if args.seed:
        parts = [float(v) for v in args.seed.split(",")]
        if len(parts) != 3:
            parser.error("--seed wants X,Y,Z")
        seed = (parts[0], parts[1], parts[2])

    legs = []
    for spec in args.logs:
        path, _, mode = spec.partition(":")
        track = read_track(Path(path))
        if mode == "reverse":
            track = list(reversed(track))
        elif mode:
            parser.error(f"unknown log mode {mode!r} (only :reverse)")
        print(f"leg {path}: {len(track)} points" + (" (reversed)" if mode else ""))
        legs.append(track)

    chain = stitch(legs, seed=seed)
    points = decimate(chain, args.spacing)
    if len(points) < 2:
        print("not enough track points", file=sys.stderr)
        return 1
    payload = beats_payload(
        points, args.id_prefix, args.radius, args.map_id, args.goal_id,
        navigation_mode=args.navigation_mode, allow_jump=args.allow_jump,
    )
    total = sum(planar(a, b) for a, b in zip(chain, chain[1:]))
    print(
        f"chain {len(chain)} points, {total:.0f} yd walked -> "
        f"{len(payload['beats'])} beats @ {args.spacing:g} yd"
    )
    if args.write:
        lua_path = Path(args.out_prefix + ".lua")
        json_path = Path(args.out_prefix + ".json")
        lua_path.write_text(emit_lua(payload), encoding="utf-8")
        json_path.write_text(
            json.dumps(payload, indent=2) + "\n", encoding="utf-8"
        )
        print(f"wrote {lua_path} and {json_path}")
    else:
        for b in payload["beats"]:
            print(f'  {b["id"]}: ({b["x"]}, {b["y"]}, {b["z"]})')
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))
