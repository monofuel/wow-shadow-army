## Producer tests for gen_objective_areas typed objective identities.
## Synthetic QuestData and quest_template rows only (fixtures/objective_ids);
## the one-record WorldMapArea.dbc is written into a private temp dir that is
## removed even when a check or the run itself fails.
##
## The typed table rendered from the fixtures (with the CLI's own provenance
## line) must equal fixtures/objective_ids/expected_areas.lua byte for byte.
## lua/tests/test_objective_identity.lua runs the consumer against that same
## golden, so producer drift fails here and consumer drift fails there.
##
## Run: nim r --hints:off --warnings:off tools/tests/test_gen_objective_areas.nim

import std/[os, streams, strutils, tables, tempfiles]
import ../gen_objective_areas

let fixtures = currentSourcePath().parentDir / "fixtures" / "objective_ids"

var passed, failed = 0
proc check(cond: bool, name: string) =
  if cond: inc passed
  else:
    inc failed
    stderr.writeLine "FAIL: " & name

proc rejects(tsv: string): bool =
  ## True when the definition parser refuses the whole input.
  try: discard parseObjectiveDefs(tsv, 10)
  except ValueError: return true
  false

proc ids(quests: Table[int, Quest], q: int): seq[string] =
  for o in quests[q].objectives:
    result.add(if o.idField == "": "-" else: o.idField & "=" & $o.id)

proc run(tmp: string) =
  # One WorldMapArea record: area 9900 on map 1, a 2000-yard square at origin.
  let dbc = tmp / "WorldMapArea.synthetic.dbc"
  block:
    var s = newFileStream(dbc, fmWrite)
    s.write("WDBC")
    for v in [1'i32, 8, 32, 1]: s.write(v)
    for v in [1'i32, 1, 9900, 0]: s.write(v)
    for v in [1000'f32, -1000, 1000, -1000]: s.write(v)
    s.write('\0')
    s.close()

  let boxes = readBoxes(dbc)
  let questData = fixtures / "QuestData.synthetic.lua"
  let tsv = readFile(fixtures / "objective_ids.synthetic.tsv")
  let defs = parseObjectiveDefs(tsv, 10)

  # Legacy path: no ids anywhere, header unchanged.
  let legacy = render(parseQuests(questData), boxes)
  check("_id" notin legacy.body and "entry =" notin legacy.body,
    "without --objective-ids nothing typed is emitted")
  check(legacy.body.startsWith(
    "-- generated by gen_objective_areas; do not edit by hand\n" &
    "-- source: QuestData.lua objective spots + WorldMapArea.dbc\n" &
    "-- spots are WORLD yards {map,x,y}; objective order = QuestData order\nreturn {\n"),
    "legacy header unchanged")

  var quests = parseQuests(questData)
  let stats = applyIds(quests, defs)
  check(ids(quests, 9101) == @["item_id=7101", "item_id=7102"],
    "two same-kind item rows keep their definition ids in order")
  check(ids(quests, 9102) == @["-"], "dropped slot (2 defined, 1 guided): no ids")
  check(ids(quests, 9103) == @["-", "-"], "count disagreement: no ids")
  check(ids(quests, 9104) == @["-", "-"], "repeated item id: no ids")
  check(ids(quests, 9105) == @["-", "-"], "conflicting rows at one patch: no ids")
  check(ids(quests, 9106) == @["item_id=7161", "item_id=7162"],
    "highest patch <= 10 wins; patch 11 ignored")
  check(ids(quests, 9107) == @["-", "-"], "no definition: no ids")
  check(ids(quests, 9108) == @["item_id=7181", "item_id=7182"], "SrcItemId slot skipped")
  check(ids(quests, 9109) == @["entry=5190", "object_entry=5191", "item_id=7191"],
    "creature, game object and item slots typed by sign and block")
  check(ids(quests, 9110) == @["-"], "QuestData row without count: no ids")
  check(stats.attributed == 4 and stats.dropped == 1 and stats.mismatch == 2 and
    stats.duplicate == 1 and stats.conflict == 1 and stats.noDefinition == 1,
    "run summary counts every outcome: " & $stats)

  # Malformed definition input is fatal, not partially read.
  check(rejects("entry\tpatch\n9101\t0\n"), "missing columns rejected")
  check(rejects(tsv.replace("\t7101\t", "\tNULL\t")), "non-integer cell rejected")
  check(rejects(""), "empty input rejected")

  # Header / row shape. rows[0] is the header; the rest are data rows.
  let rows = tsv.strip(leading = false).splitLines()
  proc joined(ls: seq[string]): string = ls.join("\n") & "\n"
  proc rowOf(prefix: string): int =
    for i in 1 ..< rows.len:
      if rows[i].startsWith(prefix): return i
    raise newException(KeyError, "fixture row " & prefix)

  var dup = rows
  dup[0].add "\tReqItemId1"
  for i in 1 ..< dup.len: dup[i].add "\t7999"
  check(rejects(joined(dup)),
    "duplicate header column rejected (a later ReqItemId1 must not win)")
  var dupTrim = rows
  dupTrim[0].add "\t ReqItemId1 "
  for i in 1 ..< dupTrim.len: dupTrim[i].add "\t7999"
  check(rejects(joined(dupTrim)), "duplicate header after trimming rejected")
  var extraCol = rows
  extraCol[0].add "\tUnusedColumn"
  for i in 1 ..< extraCol.len: extraCol[i].add "\t0"
  check(not rejects(joined(extraCol)),
    "control: a unique extra column with matching rows is accepted")

  var long = rows
  long[rowOf("0\t9101\t")].add "\t0"
  check(rejects(joined(long)), "row with an extra cell rejected")
  var longIgnored = rows
  longIgnored[rowOf("11\t9106\t")].add "\t0"
  check(rejects(joined(longIgnored)),
    "extra cell on an ignored (patch > max) row still rejected")
  var trailing = rows
  trailing[rowOf("0\t9101\t")].add "\t"
  check(rejects(joined(trailing)), "row with a trailing empty cell rejected")
  var short = rows
  let si = rowOf("0\t9109\t")
  short[si] = short[si].rsplit('\t', 1)[0]
  check(rejects(joined(short)), "row with a missing cell rejected")

  # count is read after kind: a label containing ", count = " is not the count.
  let tricky = tmp / "QuestData.label-count.lua"
  writeFile(tricky, "ShadowArmyQuestData = {\n" &
    "[\"Tricky\"] = {\n" &
    "id = 9101, level = 5, minLevel = 3, zone = 9900,\n" &
    "objectives = {\n" &
    "{ label = \"Bag, count = 9, Satchel\", kind = \"item\", count = 4, from = { \"Alpha Raider\" }, spots = { {zone = 9900, x = 50.0, y = 35.0} } },\n" &
    "{ label = \"Beta Satchel\", kind = \"item\", count = 6, from = { \"Beta Raider\" }, spots = { {zone = 9900, x = 50.0, y = 57.5} } },\n" &
    "},\n},\n" &
    "[\"Tricky Old\"] = {\n" &
    "id = 9110, level = 5, minLevel = 3, zone = 9900,\n" &
    "objectives = {\n" &
    "{ label = \"Old, count = 1, A\", kind = \"item\", from = { \"Alpha Raider\" }, spots = { {zone = 9900, x = 50.0, y = 35.0} } },\n" &
    "},\n},\n}\n")
  var trickyQuests = parseQuests(tricky)
  discard applyIds(trickyQuests, defs)
  check(trickyQuests[9101].objectives[0].count == 4 and
    ids(trickyQuests, 9101) == @["item_id=7101", "item_id=7102"],
    "label containing ', count = 9,' does not override the real count")
  check(trickyQuests[9110].objectives[0].count == -1 and
    ids(trickyQuests, 9110) == @["-"],
    "label count text on a count-less row is not read as a count")

  let header = idSummary(stats, quests.len, 10)
  let typed = render(quests, boxes, header)
  check("{kind = \"item\", item_id = 7101, from = {\"Alpha Raider\"}, spots = {{1,300.0,0.0}}}" in
    typed.body, "typed row keeps the legacy world transform")
  check("-- " & header & "\nreturn {" in typed.body, "provenance line")
  let golden = readFile(fixtures / "expected_areas.lua")
  check(typed.body == golden,
    "typed render equals fixtures/objective_ids/expected_areas.lua byte for byte")
  if typed.body != golden:
    stderr.writeLine "---- actual render ----\n" & typed.body

let tmp = createTempDir("gen_objective_areas_", "")
try:
  run(tmp)
finally:
  removeDir(tmp)

echo "test_gen_objective_areas: ", passed, " passed, ", failed, " failed"
if failed > 0: quit(1)
